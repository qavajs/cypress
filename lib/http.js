import { When } from '@qavajs/cypress-runner-adapter';
import { dataTable2Object } from './utils.js';
import { logRequest } from './logger.js';

/** @typedef {import('./memoryValue.js').MemoryValue} MemoryValue */
/** @typedef {Cypress.Chainable<JQuery<HTMLElement>>} Locator */
/** @typedef {(actual: any, expected: any) => void} Validation */
/** @typedef {{ raw(): string[][], hashes(): Array<Record<string, string>> }} DataTable */

/**
 * GraphQL request template.
 * `query` and `variables` are stored in `body`, so the request can be passed to `cy.request` as is.
 */
export class GraphQl {
    method = 'POST';
    headers = { 'Content-Type': 'application/json' };
    body = { query: '', variables: {} };

    get query() {
        return this.body.query;
    }

    set query(query) {
        this.body = { ...this.body, query };
    }

    get variables() {
        return this.body.variables;
    }

    /**
     * @param {string | object} variables - JSON string or object
     */
    set variables(variables) {
        this.body = { ...this.body, variables: typeof variables === 'string' ? JSON.parse(variables) : variables };
    }
}

/**
 * Build multipart form data from data table rows.
 * Rows with `filename` or `contentType` are added as files, other rows as plain fields.
 * @param {import('./setup.js').QavajsCypressWorld} world
 * @param {Array<Record<string, string>>} records - data table hashes
 * @return {FormData}
 */
export function toFormData(world, records) {
    const resolve = value => (value === undefined || value === '') ? undefined : world.value(value);
    const formData = new FormData();
    for (const record of records) {
        const key = resolve(record.key);
        const value = resolve(record.value) ?? '';
        const fileName = resolve(record.filename);
        const type = resolve(record.contentType);
        if (value instanceof Blob) {
            formData.append(key, value, fileName);
        } else if (fileName !== undefined || type !== undefined) {
            formData.append(key, new Blob([value], { type: type ?? '' }), fileName ?? 'blob');
        } else {
            formData.append(key, typeof value === 'object' ? JSON.stringify(value) : String(value));
        }
    }
    return formData;
}

/**
 * Convert request template to `cy.request` options.
 * `cy.request` serializes objects as JSON, so FormData body is encoded to multipart string
 * with the matching `Content-Type` header. File parts are encoded as UTF-8 text.
 * @param {Partial<Cypress.RequestOptions>} request - request template
 * @return {Partial<Cypress.RequestOptions> | Promise<Partial<Cypress.RequestOptions>>}
 */
export function toCypressRequest(request) {
    if (!(request.body instanceof FormData)) return { ...request };
    const encoded = new Response(request.body);
    // multipart boundary is generated by the encoder, so content type set by user is replaced
    const headers = Object.fromEntries(
        Object.entries(request.headers ?? {}).filter(([name]) => name.toLowerCase() !== 'content-type')
    );
    return encoded.text().then(body => ({
        ...request,
        headers: { ...headers, 'Content-Type': encoded.headers.get('content-type') },
        body
    }));
}

/**
 * Create request template and save it to memory
 * @param {string} method - HTTP method (GET, POST, PUT, DELETE, ...)
 * @param {MemoryValue} key - memory key
 * @example I create 'GET' request 'request'
 */
When('I create {string} request {value}', function (method, key) {
    cy.then(() => {
        key.set({ method });
    });
});

/**
 * Create GraphQL request template (POST, JSON) and save it to memory
 * @param {MemoryValue} key - memory key
 * @example I create GraphQL request 'request'
 */
When('I create GraphQL request {value}', function (key) {
    cy.then(() => {
        key.set(new GraphQl());
    });
});

/**
 * Add headers from two-column data table to request
 * @param {MemoryValue} requestKey - request
 * @param {DataTable} headersDataTable - headers data table
 * @example
 * I add headers to '$request':
 *   | Content-Type | application/json |
 */
When('I add headers to {value}:', /** @this {import('./setup.js').QavajsCypressWorld} */ function (requestKey, headersDataTable) {
    cy.then(() => {
        const request = requestKey.value();
        request.headers = Object.assign({}, request.headers, dataTable2Object(this, headersDataTable));
    });
});

/**
 * Add headers object to request
 * @param {MemoryValue} headersKey - headers object
 * @param {MemoryValue} requestKey - request
 * @example I add '$headers' headers to '$request'
 */
When('I add {value} headers to {value}', function (headersKey, requestKey) {
    cy.then(() => {
        const request = requestKey.value();
        request.headers = Object.assign({}, request.headers, headersKey.value());
    });
});

