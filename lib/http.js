/**
 * Set query or variables (JSON) of GraphQL request
 * @param {'query' | 'variables'} property - GraphQL property
 * @param {MemoryValue} requestKey - request
 * @param {string} valueString - query or variables JSON
 * @example
 * I add query to GraphQL '$request':
 * """
 * query {
 *     characters(page: 2) { results { name } }
 * }
 * """
 * @example
 * I add variables to GraphQL '$request':
 * """
 * { "page": 2 }
 * """
 */
When('I add {gqlRequestProperty} to GraphQL {value}:', /** @this {import('./setup.js').QavajsCypressWorld} */ function (property, requestKey, valueString) {
    cy.then(() => {
        const request = requestKey.value();
        request[property] = this.value(valueString);
    });
});

/**
 * Set multipart form data body of request.
 * Rows with `filename` or `contentType` are sent as files (content is encoded as UTF-8 text), other rows as plain fields.
 * @param {MemoryValue} requestKey - request
 * @param {DataTable} dataTable - form data table with key, value, filename and contentType columns
 * @example
 * I add form data body to '$request':
 *   | key      | value      | filename | contentType |
 *   | formKey  | formValue  |          |             |
 *   | fileKey  | $fileText  | file.txt | text/plain  |
 */
When('I add form data body to {value}:', /** @this {import('./setup.js').QavajsCypressWorld} */ function (requestKey, dataTable) {
    cy.then(() => {
        const request = requestKey.value();
        request.body = toFormData(this, dataTable.hashes());
    });
});

